test_that("an analysis switched memory <-> stream exports the engine of its latest ok run", {
  withr::local_options(sr.stream_chunk_rows = 700)
  p <- .sc_locked(.sca_spec(), env = environment())
  p <- sr_run(p, "a1")
  expect_true(isTRUE(p$state$runs$a1$ok), info = p$state$runs$a1$error)
  s_mem <- sr_analysis_script(p, "a1")
  # switched but not run again: the export is still the memory run's
  p <- sr_engine_switch(p, "a1", "stream", "moved to locked16")
  expect_identical(sr_analysis_script(p, "a1"), s_mem)
  p <- sr_run(p, "a1")
  expect_true(isTRUE(p$state$runs$a1$ok), info = p$state$runs$a1$error)
  expect_identical(p$state$runs$a1$ok_engine, "stream")
  s_st <- sr_analysis_script(p, "a1")
  expect_true(grepl(".parquet", s_st, fixed = TRUE))
  expect_false(grepl(".rds", s_st, fixed = TRUE))
  res <- .sca_rerun(s_st, p$paths$dir)
  expect_equal(res$a1$coef, .sca_stored(p, "a1")$coef, tolerance = 1e-12)
  # and back: the memory run again gives the first text
  p <- sr_engine_switch(p, "a1", "memory", "back on the laptop")
  expect_identical(sr_analysis_script(p, "a1"), s_st)
  p <- sr_run(p, "a1")
  expect_true(isTRUE(p$state$runs$a1$ok), info = p$state$runs$a1$error)
  expect_identical(sr_analysis_script(p, "a1"), s_mem)
})

# A frozen stream project (run, frozen): list(p, sha).
.sca_frozen_stream <- function(env = parent.frame()) {
  withr::local_options(sr.stream_chunk_rows = 700)
  p <- .sc_locked(.sca_spec(engine = "stream"), env = env)
  p <- sr_run(p, "a1")
  stopifnot(isTRUE(p$state$runs$a1$ok))
  p <- sr_freeze(p)
  list(p = p, sha = p$state$runs$a1$ok_extract_sha)
}

test_that("freeze lists the parquet extract", {
  f <- .sca_frozen_stream(environment())
  m <- sr_freeze_manifest(f$p, "submission-v1")
  rel <- paste0("data/extracts/", f$sha, ".parquet")
  ent <- Filter(function(x) identical(x$path, rel), m$files)
  expect_length(ent, 1L)
  expect_identical(ent[[1]]$kind, "extract")
  expect_identical(ent[[1]]$sha256, f$sha)
  expect_false(any(vapply(m$files, function(x) identical(x$path, paste0("data/extracts/", f$sha, ".rds")), NA)))
  expect_true(isTRUE(sr_freeze_verify(f$p, "submission-v1")$ok))
  # the frozen analysis.R is the stream one
  code <- readLines(file.path(.sr_freeze_dir(f$p, "submission-v1"), "analysis.R"), warn = FALSE)
  expect_true(any(grepl(rel, code, fixed = TRUE)))
  # a missing parquet extract stops the freeze gate
  unlink(file.path(f$p$paths$dir, rel))
  expect_error(sr_freeze(f$p), "the extract of 'a1' is missing")
})

test_that("full, lean and auto export then import round-trip the parquet", {
  f <- .sca_frozen_stream(environment())
  rel <- paste0("data/extracts/", f$sha, ".parquet")
  root <- withr::local_tempdir()
  for (mode in c("full", "lean", "auto")) {
    path <- file.path(root, paste0("study-", mode, ".srproj"))
    f$p <- sr_srproj_export(f$p, path, data = mode)
    q <- sr_srproj_import(path, file.path(root, paste0("imp-", mode)))
    withr::defer(sr_project_close(q))
    expect_true(isTRUE(q$import$verify$ok), info = mode)
    expect_true(file.exists(file.path(q$paths$dir, rel)), info = mode)
    expect_identical(sr_sha256_file(file.path(q$paths$dir, rel)), f$sha, info = mode)
    if (identical(mode, "lean")) expect_identical(q$import$parts_missing, "t")
    expect_identical(sr_result(q, "a1"), sr_result(f$p, "a1"), info = mode)
  }
})

test_that("archive panel accepts a parquet extract", {
  withr::local_options(sr.stream_chunk_rows = 700)
  p <- .sc_locked(.sca_spec(engine = "stream"), env = environment())
  p <- sr_run(p, "a1")
  expect_true(isTRUE(p$state$runs$a1$ok), info = p$state$runs$a1$error)
  g <- .sr_ar_freeze_gates(p)
  expect_true(g$ok[g$gate == "Stored results present"], info = g$reason[g$gate == "Stored results present"])
  unlink(file.path(p$paths$dir, "data", "extracts", paste0(p$state$runs$a1$ok_extract_sha, ".parquet")))
  g <- .sr_ar_freeze_gates(p)
  expect_false(g$ok[g$gate == "Stored results present"])
  expect_identical(g$reason[g$gate == "Stored results present"], "the extract of 'a1' is missing; run it again")
})

