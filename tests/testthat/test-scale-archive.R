  }
})

test_that("the pre-P1e fixture project exports the same text and passes the key check", {
  ev <- testthat::test_path("fixtures", "pre-p1e-lock", "events.jsonl")
  events <- sr_events_read(ev)
  state <- sr_state_replay(events)
  a <- state$analyses$a1
  spec <- .sr_spec_from_state(a$spec)
