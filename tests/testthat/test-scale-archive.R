# analysis.R and the archive for streaming analyses (P1e.1 Task 12, rulings R5 and R6): the script block
# uses the run spec of the latest ok run (its engine and chunk), a stream block reads the Parquet extract,
# and freeze, srproj export / import and the Archive panel take the extract extension from
# ok_extract_kind. Synthetic data only.

.sca_layers <- function() {
  list(missing = "cc", weights = "none", matching = FALSE, resampling = "none",
       framework = "frequentist", clustered = FALSE)
}

# A logistic spec with a factor term (grp has a non-ASCII level) and robust SEs; extra fields from `...`.
.sca_spec <- function(...) {
  s <- list(purpose = "explain-causal", outcome = "y", exposure = "sex", exposure_ref = "F",
            terms = list(list(var = "x1"), list(var = "grp", type = "factor")),
            layers = .sca_layers(), seed = 42L, se = "robust")
  x <- list(...)
  for (nm in names(x)) s[[nm]] <- x[[nm]]
  s
}

.sca_stored <- function(p, id) {
  readRDS(file.path(p$paths$fits, paste0(p$state$runs[[id]]$ok_key, ".rds")))$value
}

# Source `script` in a fresh R process with SR_PROJECT_DIR set; returns the sr_results list.
.sca_rerun <- function(script, dir) {
  f <- tempfile("analysis-", fileext = ".R")
  on.exit(unlink(f), add = TRUE)
  writeLines(script, f, useBytes = TRUE)
  callr::r(function(f, d) {
    Sys.setenv(SR_PROJECT_DIR = d)
    e <- new.env()
    sys.source(f, envir = e)
    e$sr_results
  }, args = list(f = f, d = dir), libpath = .libPaths(), user_profile = FALSE, wd = tempdir())
}

# The block as .sr_script_block built it before P1e.1 Task 12 (raw state spec, the .rds prologue).
.sca_old_block <- function(project, id, a) {
  r <- project$state$runs[[id]]
  key <- r$ok_key
  sha <- r$ok_extract_sha
  route <- sr_route_get(a$route, a$route_version)
  spec <- .sr_spec_from_state(a$spec)
  body <- sr_compile(route, spec)
  lib <- r$ok_lib_hash
  hw <- r$ok_hw_fp
  if (is.null(lib) || length(lib) != 1L || is.na(lib)) lib <- sr_libsnap_hash()
  if (is.null(hw) || length(hw) != 1L || is.na(hw)) hw <- sr_hw_fingerprint()
  now <- sr_content_hash(sha, list(route = .sr_route_key(a$route, a$route_version), spec = spec), spec$seed,
                         libsnap_hash = lib, hw_fp = hw)
  if (!identical(now, key)) stop("old logic: recompile changed", call. = FALSE)
  ex <- list(rel = paste0("data/extracts/", sha, ".rds"), sha = sha)
  label <- gsub("[^A-Za-z0-9_. -]", "?", as.character(a$label %||% "unlabelled")[1L])
  paste(c(
    sprintf("# ---- %s (%s; route %s v%s) ----", id, label, a$route, a$route_version),
    sprintf("sr_results[[%s]] <- local({", .sr_lit(id)),
    sr_rng_preamble(spec$seed),
    .sr_run_prologue(ex),
    body,
    "})"), collapse = "\n")
}

# The whole script as it was built before Task 12 (old head, old blocks).
.sca_old_script <- function(project, ids) {
  an <- .sr_wd_analyses(project)
  blocks <- vapply(ids, function(id) .sca_old_block(project, id, an[[id]]), "")
  head <- c(
    "# analysis.R - generated by StatRouter. Re-runs every reported analysis as it ran.",
    paste("# SAP SHA-256:", as.character(project$state$sap$lock$sap_hash %||% NA_character_)),
    paste0("# ", R.version.string, "; packages as in renv.lock"),
    "# Set SR_PROJECT_DIR to the project folder (the extracts are read from data/extracts/).",
    "sr_project_dir <- Sys.getenv(\"SR_PROJECT_DIR\", \".\")",
    "sr_results <- list()")
  paste0(paste(c(head, "", unlist(strsplit(paste(blocks, collapse = "\n\n"), "\n", fixed = TRUE))),
               collapse = "\n"), "\n")
}

.sca_no_path <- function(s, p) {
  bs <- intToUtf8(92L)
  expect_false(grepl(p$paths$dir, s, fixed = TRUE))
  expect_false(grepl(gsub(bs, "/", p$paths$dir, fixed = TRUE), s, fixed = TRUE))
  expect_false(grepl(gsub(bs, "/", tempdir(), fixed = TRUE), s, fixed = TRUE))
  expect_false(grepl(":/", s, fixed = TRUE))
  expect_false(grepl(paste0(":", bs), s, fixed = TRUE))
}

test_that("analysis.R reproduces a stream run", {
  withr::local_options(sr.stream_chunk_rows = 700)
  p <- .sc_locked(.sca_spec(engine = "stream"), env = environment())
  p <- sr_run(p, "a1")
  expect_true(isTRUE(p$state$runs$a1$ok), info = p$state$runs$a1$error)
  expect_identical(p$state$runs$a1$ok_extract_kind, "parquet")
  s <- sr_analysis_script(p, "a1")
  expect_error(parse(text = s), NA)
  expect_false(any(charToRaw(s) > as.raw(127L)))
  .sca_no_path(s, p)
  sha <- p$state$runs$a1$ok_extract_sha
  expect_true(grepl(paste0("data/extracts/", sha, ".parquet"), s, fixed = TRUE))
  expect_false(grepl(".rds", s, fixed = TRUE))
  expect_true(grepl(paste("# Streaming analyses need the duckdb package; the parquet extracts are read from",
                          "data/extracts/."), s, fixed = TRUE))
  expect_true(grepl("sr_duck_memory <- Sys.getenv(\"SR_DUCK_MEMORY\", \"4GB\")", s, fixed = TRUE))
  expect_true(grepl("sr_duck_threads <- 2L", s, fixed = TRUE))
  expect_true(grepl("sr_duck_temp <- tempdir()", s, fixed = TRUE))
  # the chunk of the run is in the code (the run spec, not the state spec)
  expect_true(grepl("700L", s, fixed = TRUE))
  # the option changing after the run does not change the exported code
  withr::local_options(sr.stream_chunk_rows = 333)
  expect_identical(sr_analysis_script(p, "a1"), s)
  res <- .sca_rerun(s, p$paths$dir)
  st <- .sca_stored(p, "a1")
  expect_identical(res$a1$engine, "stream")
  expect_equal(res$a1$coef, st$coef, tolerance = 1e-12)
})

