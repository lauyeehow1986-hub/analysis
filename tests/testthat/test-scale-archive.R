  key <- sr_content_hash(sha, list(route = .sr_route_key(a$route, a$route_version), spec = spec), spec$seed,
                         libsnap_hash = "lib", hw_fp = "hw")
  # a run.completed as written before P1e (no engine, extract_kind or chunk)
  red <- .sr_reducer_get("run.completed")
  state <- red(state, list(ts = "2026-11-11T15:06:06.000Z",
                           payload = list(analysis = "a1", key = key, extract_sha = sha, ok = TRUE,
                                          lib_hash = "lib", hw_fp = "hw", job = "j1")))
