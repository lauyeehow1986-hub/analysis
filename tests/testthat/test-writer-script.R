# Tests for writer/script.R: analysis.R from the exact run code, and the renv-style lockfile.
# Synthetic data only (the writer fixture of helper-writer.R); the re-runs happen in callr workers.

.ws_ids <- c("t1", "a_lr", "a_cox", "a_rmst", "a_mp", "x_age")

# Source `script` in a fresh R process with SR_PROJECT_DIR set; returns the sr_results list.
.ws_rerun <- function(script, dir) {
  f <- tempfile("analysis-", fileext = ".R")
  on.exit(unlink(f), add = TRUE)
  writeLines(script, f, useBytes = TRUE)
  callr::r(function(f, d) {
    Sys.setenv(SR_PROJECT_DIR = d)
    e <- new.env()
    sys.source(f, envir = e)
    e$sr_results
  }, args = list(f = f, d = dir), libpath = .libPaths(), user_profile = FALSE, wd = tempdir())
}

.ws_stored <- function(p, id) {
  readRDS(file.path(p$paths$fits, paste0(p$state$runs[[id]]$ok_key, ".rds")))$value
}

test_that("the run reducer keeps the extract of the latest ok run next to ok_key", {
  p <- .fx_writer_project(environment())
  r <- p$state$runs$a_lr
  expect_match(r$ok_extract_sha, "^[0-9a-f]{64}$")
  expect_identical(r$ok_extract_sha, r$extract_sha)
  # a later failed run keeps the ok pair; an old event without the field still reduces
  st <- list(runs = list(a = list(ok_key = "k1", ok_extract_sha = "s1")))
  st <- .sr_reducer_get("run.completed")(st, list(payload = list(analysis = "a", key = "k2",
                                                                extract_sha = "s2", ok = FALSE)))
  expect_identical(st$runs$a$ok_key, "k1")
  expect_identical(st$runs$a$ok_extract_sha, "s1")
  st2 <- .sr_reducer_get("run.completed")(list(), list(payload = list(analysis = "b", key = "k", ok = FALSE)))
  expect_true(is.na(st2$runs$b$ok_extract_sha))
})

test_that("the script text parses, holds one block per run analysis, is ASCII and has no path", {
  p <- .fx_writer_project(environment())
  s <- sr_analysis_script(p, .ws_ids)
  expect_length(s, 1L)
  expect_error(parse(text = s), NA)
  expect_false(any(charToRaw(s) > as.raw(127L)))
  bs <- intToUtf8(92L)
  expect_false(grepl(tempdir(), s, fixed = TRUE))
  expect_false(grepl(gsub(bs, "/", tempdir(), fixed = TRUE), s, fixed = TRUE))
  expect_false(grepl(p$paths$dir, s, fixed = TRUE))
  expect_false(grepl(gsub(bs, "/", p$paths$dir, fixed = TRUE), s, fixed = TRUE))
  expect_false(grepl(paste0(":", bs), s, fixed = TRUE))   # no drive path
  expect_false(grepl(":/", s, fixed = TRUE))
  heads <- regmatches(s, gregexpr("(?m)^# ---- [^ ]+ ", s, perl = TRUE))[[1L]]
  # SAP order: the pre-specified analyses first, then the one added after the lock
  expect_identical(gsub("^# ---- | $", "", heads), c("t1", "a_lr", "a_cox", "a_rmst", "a_mp", "x_age"))
  expect_equal(lengths(regmatches(s, gregexpr("(?m)^sr_results[[]{2}", s, perl = TRUE))), 6L)
  lines <- strsplit(s, "\n", fixed = TRUE)[[1L]]
  expect_match(lines[1L], "^# analysis.R - generated by StatRouter")
  expect_identical(lines[2L], paste("# SAP SHA-256:", p$state$sap$lock$sap_hash))
  expect_identical(lines[3L], paste0("# ", R.version.string, "; packages as in renv.lock"))
  expect_true("sr_results <- list()" %in% lines)
  expect_true(any(grepl('Sys.getenv("SR_PROJECT_DIR", ".")', lines, fixed = TRUE)))
  # the order of ids given does not matter: SAP order wins
  expect_identical(sr_analysis_script(p, rev(.ws_ids)), s)
  # the code of the run is in the script, byte for byte
  a <- p$state$analyses$a_lr
  body <- sr_compile(sr_route_get(a$route, a$route_version), .sr_spec_from_state(a$spec))
  expect_true(grepl(body, s, fixed = TRUE))
})

test_that("an analysis without an ok run, or an unknown one, is refused", {
  p <- .fx_writer_project(environment())
  expect_error(sr_analysis_script(p, "nope"), "unknown analysis")
  expect_error(sr_analysis_script(p, character()), "ids")
  q <- p
  q$state$runs$a_lr$ok_key <- NA_character_
  expect_error(sr_analysis_script(q, "a_lr"), "no successful run")
})

test_that("sourcing the script reproduces the stored results", {
  p <- .fx_writer_project(environment())
  res <- .ws_rerun(sr_analysis_script(p, c("a_lr", "a_rmst", "t1")), p$paths$dir)
  expect_identical(names(res), c("t1", "a_lr", "a_rmst"))
  expect_identical(res[["a_lr"]], .ws_stored(p, "a_lr"))
  expect_identical(res[["a_rmst"]], .ws_stored(p, "a_rmst"))
  expect_identical(res[["t1"]], .ws_stored(p, "t1"))
})

test_that("the bootstrap variant reproduces too (seeded)", {
  p <- .fx_writer_build(environment(), boot = TRUE)
  withr::defer(sr_duck_close(p))
  withr::defer(sr_project_close(p))
  res <- .ws_rerun(sr_analysis_script(p, "a_mp"), p$paths$dir)
  expect_identical(res[["a_mp"]], .ws_stored(p, "a_mp"))
})

test_that("a spec edited after the run no longer matches: refused", {
  p <- .fx_writer_project(environment())
  q <- p
  n <- length(q$state$analyses$a_lr$spec$terms)
  q$state$analyses$a_lr$spec$terms[[n + 1L]] <- list(var = "stage")
  expect_error(sr_analysis_script(q, "a_lr"), "the code of a_lr no longer matches the run")
  expect_error(sr_analysis_script(q, "a_lr"), "no longer matches")
  # the unedited analyses still export
  expect_error(sr_analysis_script(q, c("t1", "a_cox")), NA)
})

test_that("sr_lockfile has the renv.lock shape", {
  lf <- sr_lockfile()
  expect_match(lf$R$Version, "^[0-9]+[.][0-9]+[.][0-9]+$")
  expect_identical(lf$R$Version, as.character(getRversion()))
  expect_identical(lf$R$Repositories, list())
  expect_identical(lf$Packages$survival$Version, as.character(utils::packageVersion("survival")))
  expect_true(all(c("officer", "flextable") %in% names(lf$Packages)))
  expect_identical(names(lf$Packages), sort(names(lf$Packages), method = "radix"))
  for (nm in names(lf$Packages)) {
    e <- lf$Packages[[nm]]
    expect_identical(e$Package, nm)
    expect_identical(e$Source, "Repository")
    expect_identical(e$Repository, "CRAN")
  }
  snap <- sr_libsnap()
  expect_identical(lf$StatRouter$libsnap_hash, sr_libsnap_hash(snap))
  expect_identical(lf$StatRouter$snapshot_date, snap$snapshot_date)
  # a package that is not installed is left out
  snap2 <- sr_libsnap(c("survival", "notapkgxyz"))
  expect_identical(names(sr_lockfile(snap2)$Packages), "survival")
  expect_error(.sr_json(lf), NA)
})
