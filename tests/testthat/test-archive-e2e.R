test_that("P1 exit 7: export -> freeze -> .srproj -> import elsewhere -> identical hashes; library change -> re-baseline", {
  p <- .fx_writer_project()
  p <- sr_export(p)                                           # outputs are part of the freeze
  p <- sr_freeze(p, "submission-v1")
  m <- sr_freeze_manifest(p, "submission-v1")
  expect_true(any(vapply(m$files, function(f) f$kind == "export", NA)))
  arch <- file.path(withr::local_tempdir(), "submission-v1.srproj")
  p <- sr_srproj_export(p, arch, data = "full")
  dest <- file.path(withr::local_tempdir(), "drive-b", "study")
  dir.create(dirname(dest))
  q <- sr_srproj_import(arch, dest)
  withr::defer(sr_project_close(q))
  expect_true(q$import$verify$ok)
  expect_identical(sr_freeze_manifest(q, "submission-v1"), m)
  for (id in names(m$runs)) expect_identical(sr_result(q, id), sr_result(p, id))
  expect_true(sr_project_verify(q)$ok)
  withr::local_options(sr.cran_snapshot = "2099-01-01")
  expect_error(sr_run(q, "a_lr"), "sr_rebaseline")
  expect_identical(sr_rebaseline_diff(q)$item, "snapshot_date")
  q <- sr_rebaseline(q, "reviewer re-run under the revision library")
  q <- sr_run(q, "a_lr")
  r <- sr_freeze_results_diff(q, "submission-v1")
  expect_identical(r$status[r$analysis == "a_lr"], "identical")
  ev <- readLines(q$paths$events, warn = FALSE)
  expect_false(any(grepl(normalizePath(dirname(arch), winslash = "/"), ev, fixed = TRUE)))   # no absolute archive path
})
