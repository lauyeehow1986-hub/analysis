# writer/script.R - the exported analysis.R and the renv-style lockfile.
#
# analysis.R is the code that ran, not a re-derivation of it: for every reported analysis it holds the
# RNG preamble, the extract prologue and sr_compile(route, spec), the three parts sr_run() sends to the
# worker, in a local() of their own. Sourced with SR_PROJECT_DIR set to the project folder it
# reproduces the stored results. Before it writes a block, the script checks that the code still is the
# code of the run: the content hash of (extract, route, spec, seed) must equal the key of the latest ok
# run, otherwise a recompile changed the code and the analysis must be run again. The check is about the
# code, not the machine: the key is recomputed with the library hash and hardware fingerprint recorded
# with that run (ok_lib_hash, ok_hw_fp; the current values only for a run recorded without them), so an
# export on another machine or after a package update still passes. The text is ASCII
# (.sr_lit escapes data strings) and holds no path: the project folder comes from the environment.

#' The analysis.R text for the analyses `ids`, each of which has an ok run, in SAP order (pre-specified
#' analyses first, then those added after the lock, each group in plan order).
#' @param project an open project (locked SAP).
#' @param ids character vector of analysis ids.
#' @return one string, LF line endings, ASCII.
sr_analysis_script <- function(project, ids) {
  if (!is.character(ids) || !length(ids) || anyNA(ids) || any(!nzchar(ids))) {
    stop("ids must be a character vector naming at least one analysis", call. = FALSE)
  }
  an <- .sr_wd_analyses(project)
  unknown <- setdiff(ids, names(an))
  if (length(unknown)) {
    stop("unknown analysis ", paste(vapply(unknown, .sr_sap_q, ""), collapse = ", "), call. = FALSE)
  }
  keep <- names(an)[names(an) %in% ids]
  pre <- vapply(keep, function(id) isTRUE(an[[id]]$prespecified), NA)
  keep <- c(keep[pre], keep[!pre])

  blocks <- vapply(keep, function(id) .sr_script_block(project, id, an[[id]]), "")
  head <- c(
    "# analysis.R - generated by StatRouter. Re-runs every reported analysis as it ran.",
    paste("# SAP SHA-256:", as.character(project$state$sap$lock$sap_hash %||% NA_character_)),
    paste0("# ", R.version.string, "; packages as in renv.lock"),
    "# Set SR_PROJECT_DIR to the project folder (the extracts are read from data/extracts/).",
    "sr_project_dir <- Sys.getenv(\"SR_PROJECT_DIR\", \".\")",
    "sr_results <- list()")
  out <- paste0(paste(c(head, "", unlist(strsplit(paste(blocks, collapse = "\n\n"), "\n", fixed = TRUE))),
                      collapse = "\n"), "\n")
  if (any(charToRaw(out) > as.raw(127L))) {
    stop("the script holds a non-ASCII character; data strings must be escaped", call. = FALSE)
  }
  parsed <- tryCatch(parse(text = out, keep.source = FALSE), error = function(e) e)
  if (inherits(parsed, "error")) {
    stop("the script does not parse: ", conditionMessage(parsed), call. = FALSE)
  }
  out
}

# One analysis block, or an error when the analysis has no ok run or its code no longer is the run's.
.sr_script_block <- function(project, id, a) {
  r <- project$state$runs[[id]]
  key <- r$ok_key
  sha <- r$ok_extract_sha
  if (is.null(key) || length(key) != 1L || is.na(key)) {
    stop("analysis ", .sr_sap_q(id), " has no successful run", call. = FALSE)
  }
  if (is.null(sha) || length(sha) != 1L || is.na(sha)) {
    stop("the extract of the latest ok run of ", .sr_sap_q(id), " is not recorded; run it again", call. = FALSE)
  }
  route <- sr_route_get(a$route, a$route_version)
  spec <- .sr_spec_from_state(a$spec)
  if (is.null(spec$seed)) stop("the spec of ", .sr_sap_q(id), " has no seed", call. = FALSE)
  body <- sr_compile(route, spec)
  lib <- r$ok_lib_hash
  hw <- r$ok_hw_fp
  if (is.null(lib) || length(lib) != 1L || is.na(lib)) lib <- sr_libsnap_hash()
  if (is.null(hw) || length(hw) != 1L || is.na(hw)) hw <- sr_hw_fingerprint()
  now <- sr_content_hash(sha, list(route = .sr_route_key(a$route, a$route_version), spec = spec), spec$seed,
                         libsnap_hash = lib, hw_fp = hw)
  if (!identical(now, key)) {
    stop("the code of ", id, " no longer matches the run (recompile changed); run it again", call. = FALSE)
  }
  ex <- list(rel = paste0("data/extracts/", sha, ".rds"), sha = sha)
  label <- gsub("[^A-Za-z0-9_. -]", "?", as.character(a$label %||% "unlabelled")[1L])
  paste(c(
    sprintf("# ---- %s (%s; route %s v%s) ----", id, label, a$route, a$route_version),
    sprintf("sr_results[[%s]] <- local({", .sr_lit(id)),
    sr_rng_preamble(spec$seed),
    .sr_run_prologue(ex),
    body,
    "})"), collapse = "\n")
}

#' The renv.lock-shaped list of the library the results were computed with: the R version, the
#' installed packages of the snapshot (a package that is not installed is left out) sorted by name,
#' and a StatRouter element with the snapshot date and the snapshot hash. Written as JSON by the export.
#' @param snap a library snapshot (sr_libsnap()).
sr_lockfile <- function(snap = sr_libsnap()) {
  vers <- snap$pkgs
  vers <- vers[!is.na(vers)]
  vers <- vers[order(names(vers), method = "radix")]
  pk <- lapply(stats::setNames(names(vers), names(vers)), function(n) {
    list(Package = n, Version = unname(vers[[n]]), Source = "Repository", Repository = "CRAN")
  })
  list(R = list(Version = as.character(getRversion()), Repositories = list()),
       Packages = pk,
       StatRouter = list(snapshot_date = snap$snapshot_date, libsnap_hash = sr_libsnap_hash(snap)))
}
